async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const filePath = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await walk(filePath))
    else if (sourceExtensions.has(path.extname(entry.name))) files.push(filePath)
  }

  return files
}

async function writeIfChanged(filePath, contents) {
  try {
    const current = await readFile(filePath)
    if (Buffer.compare(current, contents) === 0) return false
  } catch {
    // The initial generation creates the committed local artifact.
  }

  await writeFile(filePath, contents)
  return true
}

const sourceFiles = [...await walk(sourceRoot), path.resolve('index.html')].sort()
const sourceText = (await Promise.all(sourceFiles.map((filePath) => readFile(filePath, 'utf8')))).join('')
const usedCharacters = [...new Set([...`${printableAscii}${sourceText}`])]
  .sort((left, right) => left.codePointAt(0) - right.codePointAt(0))
  .join('')

await mkdir(outputRoot, { recursive: true })

const css = [
  '/* Generated by scripts/build-local-fonts.mjs from pinned Fontsource sources. */',
  ...fontDefinitions.map(({ family, weight, output, variable }) => `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${weight};\n  src: url('../assets/fonts/${output}') format('${variable ? 'woff2-variations' : 'woff2'}');\n}`),
].join('\n\n') + '\n'

let changed = 0
for (const font of fontDefinitions) {
  const subset = await subsetFont(await readFile(font.source), usedCharacters, {
    targetFormat: 'woff2',
    preserveNameIds: [1, 2, 4, 6],
  })
  if (await writeIfChanged(path.join(outputRoot, font.output), subset)) changed += 1
}

if (await writeIfChanged(cssOutput, Buffer.from(css))) changed += 1

const fontBytes = await Promise.all(fontDefinitions.map(async ({ output }) => (await stat(path.join(outputRoot, output))).size))
console.log(`Generated ${fontDefinitions.length} local font subsets (${fontBytes.reduce((sum, size) => sum + size, 0)} bytes; ${changed} files changed).`)
